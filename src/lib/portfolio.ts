// RozgarAI — Portfolio Builder Agent
// Generates a one-page static HTML portfolio from an Analyzer result.
// Self-contained (inline CSS, no external assets except the GitHub avatar),
// so the file works offline and can be hosted anywhere for free.

import type { Analysis } from "./analyzer";

function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export function portfolioFileName(username: string): string {
  return `${username.toLowerCase().replace(/[^a-z0-9-]/g, "")}-portfolio.html`;
}

export function buildPortfolioHtml(a: Analysis): string {
  const name = esc(a.name || a.username);
  const bio = a.bio ? esc(a.bio) : "Aspiring software developer, building in public on GitHub.";
  const location = a.location ? esc(a.location) : "India";
  const langs = a.languages
    .slice(0, 6)
    .map(
      (l) => `<div class="lang"><span>${esc(l.language)}</span><div class="bar"><div style="width:${Math.round(l.share * 100)}%"></div></div><span class="pct">${Math.round(l.share * 100)}%</span></div>`,
    )
    .join("\n");
  const strengths = a.strengths
    .map((s) => `<li>${esc(s)}</li>`)
    .join("\n");
  const repos = a.topRepos
    .map(
      (r) => `<div class="repo"><a href="${esc(r.url)}" target="_blank" rel="noreferrer">${esc(r.name)}</a><span class="meta">★ ${r.stars} · ⑂ ${r.forks}${r.language ? ` · ${esc(r.language)}` : ""}</span>${r.description ? `<p>${esc(r.description)}</p>` : ""}</div>`,
    )
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${name} — Portfolio</title>
<style>
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;background:#fafafa;color:#18181b}
.wrap{max-width:720px;margin:0 auto;padding:40px 20px}
header{display:flex;gap:20px;align-items:center}
header img{width:96px;height:96px;border-radius:50%;border:2px solid #e4e4e7}
h1{margin:0;font-size:32px} .sub{color:#52525b;margin-top:4px}
.badge{display:inline-block;margin-top:10px;padding:4px 12px;border-radius:999px;font-size:13px;font-weight:700;background:#ecfdf5;color:#047857;border:1px solid #a7f3d0}
section{margin-top:32px} h2{font-size:18px;border-bottom:2px solid #e4e4e7;padding-bottom:6px}
ul{line-height:1.7}
.lang{display:flex;align-items:center;gap:12px;margin:8px 0;font-size:14px}
.lang span:first-child{width:110px;font-weight:600}
.bar{flex:1;height:8px;background:#e4e4e7;border-radius:999px;overflow:hidden}
.bar div{height:100%;background:#0ea5e9;border-radius:999px}
.pct{width:44px;text-align:right;color:#71717a}
.repo{border:1px solid #e4e4e7;border-radius:12px;background:#fff;padding:14px 16px;margin:10px 0}
.repo a{font-weight:700;color:#047857;text-decoration:none}
.repo .meta{color:#a1a1aa;font-size:12px;margin-left:8px}
.repo p{margin:6px 0 0;color:#52525b;font-size:14px}
footer{margin-top:40px;font-size:12px;color:#a1a1aa;text-align:center}
</style>
</head>
<body>
<div class="wrap">
<header>
<img src="${esc(a.avatarUrl)}" alt="${name}">
<div>
<h1>${name}</h1>
<div class="sub">@${esc(a.username)} · ${location} · <a href="${esc(a.profileUrl)}">GitHub profile</a></div>
<div class="sub">${bio}</div>
<span class="badge">RozgarAI score ${a.score.total}/100 — ${esc(a.score.band)}</span>
</div>
</header>

<section>
<h2>About</h2>
<p>${a.publicRepos} public repositories · ${a.followers} followers · GitHub account ${a.accountAgeDays} days old${a.recentActivity.reposUpdated90d > 0 ? ` · ${a.recentActivity.reposUpdated90d} repos updated in the last 90 days` : ""}.</p>
</section>

<section>
<h2>Strengths</h2>
<ul>
${strengths}
</ul>
</section>

<section>
<h2>Languages</h2>
${langs || "<p>No language detected yet.</p>"}
</section>

<section>
<h2>Top repositories</h2>
${repos || "<p>No public repositories yet.</p>"}
</section>

<footer>Generated by RozgarAI — Code for a Billion, Track #10 Tech Employment for Youth.</footer>
</div>
</body>
</html>
`;
}
